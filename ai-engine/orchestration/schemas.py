"""Data contracts for dual-model orchestration and independent critique."""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field

from claim_extraction.schemas import EvidenceItem, ExtractedClaim
from interpretation.schemas import InterpretationFork


class DualModelReviewInput(BaseModel):
    """Input payload for dual-model primary-extraction + independent-reviewer critique."""
    claim: ExtractedClaim = Field(
        ...,
        description="Claim generated by primary extraction model."
    )
    evidence: List[EvidenceItem] = Field(
        default_factory=list,
        description="Retrieved evidence items to ground the review."
    )
    extractor_provider: Optional[str] = Field(
        default=None,
        description="Optional explicit recording of the provider that performed extraction."
    )
    extractor_model: Optional[str] = Field(
        default=None,
        description="Optional explicit recording of the model that performed extraction."
    )


class DualModelReviewOutput(BaseModel):
    """Outcome of independent dual-model review."""
    primary_claim: ExtractedClaim = Field(
        ...,
        description="Primary model extraction."
    )
    reviewer_critique_notes: Optional[str] = Field(
        default=None,
        description="Adversarial critique notes from the independent reviewer model."
    )
    is_concordant: bool = Field(
        ...,
        description="Whether primary and reviewer models reached consensus on falsifiability."
    )
    independent_review_valid: bool = Field(
        default=True,
        description="True ONLY if extractor and reviewer are genuinely independent model providers (Audit Item H-2)."
    )
    review_mode: str = Field(
        default="INDEPENDENT_DUAL_MODEL",
        description="Review execution mode: 'INDEPENDENT_DUAL_MODEL', 'DEGRADED_SAME_PROVIDER', or 'DEGRADED_SINGLE_PROVIDER'."
    )
    extractor_provider: Optional[str] = Field(
        default=None,
        description="Actual provider that executed claim extraction."
    )
    extractor_model: Optional[str] = Field(
        default=None,
        description="Actual model that executed claim extraction."
    )
    reviewer_provider: Optional[str] = Field(
        default=None,
        description="Actual provider that executed the review."
    )
    reviewer_model: Optional[str] = Field(
        default=None,
        description="Actual model that executed the review."
    )
    disagreement_reasons: List[str] = Field(
        default_factory=list,
        description="Specific axes of disagreement between the two models."
    )
    spawned_forks: List[InterpretationFork] = Field(
        default_factory=list,
        description="Interpretation forks spawned automatically from model disagreement."
    )
    consensus_warning: str = Field(
        default="Two-model agreement is not proof of factual correctness; all outputs require human verification.",
        frozen=True,
        description="Immutable disclaimer enforcing that model agreement is not verification."
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Execution telemetry and fallback diagnostic metadata."
    )
    reviewed_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp when review completed."
    )
